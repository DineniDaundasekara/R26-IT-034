function WhatIfSimulator({ phaseId, responses, ranking }) {
  const [targets, setTargets] = useState({});
  const [simulation, setSimulation] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

  useEffect(() => {
    setTargets(
      Object.fromEntries((ranking || []).map((row) => [row.feature, Number(row.current_score)]))
    );
    setSimulation(null);
    setError("");
  }, [ranking]);

  if (!ranking?.length) {
    return null;
  }

  async function runSimulation() {
    const overrides = {};
    ranking.forEach((row) => {
      const next = Number(targets[row.feature]);
      if (Math.abs(next - Number(row.current_score)) >= 0.05) {
        overrides[row.feature] = Math.round(next * 10) / 10;
      }
    });

    if (Object.keys(overrides).length === 0) {
      setError("Move at least one construct away from its current score.");
      setSimulation(null);
      return;
    }

    try {
      setLoading(true);
      setError("");
      const data = await simulateEmployability(phaseId, responses, overrides);
      setSimulation(data);
    } catch (requestError) {
      setSimulation(null);
      setError(requestError.message);
    } finally {
      setLoading(false);
    }
  }

  function resetTargets() {
    setTargets(
      Object.fromEntries(ranking.map((row) => [row.feature, Number(row.current_score)]))
    );
    setSimulation(null);
    setError("");
  }

  return (
    <div className="whatIfPanel">
      <p className="eyebrow">WHAT-IF SIMULATOR</p>
      <h2>Try a different construct score</h2>
      <p>
        Move a construct and the frozen model predicts the employability score again. This does not
        change your submitted answers.
      </p>
      <div className="whatIfControls">
        {ranking.map((row) => (
          <label className="whatIfControl" key={row.feature}>
            <div>
              <strong>{row.name}</strong>
              <small>
                Now {Number(row.current_score).toFixed(2)} · Try {Number(targets[row.feature] ?? row.current_score).toFixed(1)}
              </small>
            </div>
            <input
              type="range"
              min="1"
              max="5"
              step="0.1"
              value={targets[row.feature] ?? row.current_score}
              onChange={(event) => {
                setTargets((previous) => ({
                  ...previous,
                  [row.feature]: Number(event.target.value),
                }));
                setSimulation(null);
              }}
            />
          </label>
        ))}
      </div>
      {error && <div className="errorBox">{error}</div>}
      <div className="whatIfActions">
        <button className="submitButton whatIfButton" type="button" onClick={runSimulation} disabled={loading}>
          {loading ? "Estimating..." : "Estimate new score"}
        </button>
        <button className="secondaryButton" type="button" onClick={resetTargets}>
          Reset sliders
        </button>
      </div>
      {simulation && (
        <div className="whatIfResult">
          <div>
            <span>Current prediction</span>
            <strong>{Number(simulation.baseline_prediction).toFixed(2)}</strong>
          </div>
          <div>
            <span>What-if prediction</span>
            <strong>{Number(simulation.simulated_prediction).toFixed(2)}</strong>
          </div>
          <div>
            <span>Estimated change</span>
            <strong className={simulation.difference > 0 ? "gainPositive" : "gainNeutral"}>
              {formatGain(simulation.difference)}
            </strong>
          </div>
        </div>
      )}
    </div>
  );
}

