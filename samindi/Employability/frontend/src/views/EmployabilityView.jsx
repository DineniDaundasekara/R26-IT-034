function PhaseAssessmentPanel({ phase }) {
  const [responses, setResponses] = useState({});
  const [result, setResult] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

  const answeredCount = Object.keys(responses).length;

  function selectAnswer(code, value) {
    setResponses((previous) => ({ ...previous, [code]: value }));
  }

  async function handleSubmit(event) {
    event.preventDefault();
    setError("");

    if (answeredCount !== phase.questions.length) {
      setError(`Please answer all ${phase.questions.length} questions before submitting.`);
      return;
    }

    try {
      setLoading(true);
      const data = await predictEmployability(phase.id, responses);
      setResult(data);
      setTimeout(() => {
        document.getElementById("results")?.scrollIntoView({ behavior: "smooth" });
      }, 100);
    } catch (requestError) {
      setError(requestError.message);
    } finally {
      setLoading(false);
    }
  }

  function resetAssessment() {
    setResponses({});
    setResult(null);
    setError("");
    window.scrollTo({ top: 0, behavior: "smooth" });
  }

  const style = {
    "--phase-accent": phase.accent,
    "--phase-accent-soft": phase.accentSoft,
  };

  return (
    <div style={style}>
      <section className="hero">
        <div className="heroText">
          <p className="eyebrow">AI-ASSISTED EMPLOYABILITY ANALYSIS</p>
          <h1>{phase.heroTitle}</h1>
          <p className="heroDescription">{phase.heroDescription}</p>
        </div>
      </section>

      <section className="assessmentSection">
        <div className="sectionHeader">
          <div>
            <p className="eyebrow">{phase.assessmentTitle.toUpperCase()}</p>
            <h2>Tell us about your experience</h2>
            <p>{phase.assessmentPrompt}</p>
          </div>
        </div>

        <ProgressBar answered={answeredCount} total={phase.questions.length} />

        <form onSubmit={handleSubmit}>
          <div className="questionList">
            {phase.questions.map((question, index) => (
              <LikertQuestion
                key={question.code}
                question={question}
                index={index}
                value={responses[question.code]}
                onSelect={selectAnswer}
              />
            ))}
          </div>

          {error && <div className="errorBox">{error}</div>}

          <button className="submitButton" disabled={loading} type="submit">
            {loading ? "Analyzing..." : "Analyze Employability"}
          </button>
        </form>
      </section>

      {result && (
        <section id="results" className="resultsSection">
          <PredictionHero result={result} phase={phase} />

          <div className="constructGrid">
            {result.construct_analysis.map((item) => (
              <ConstructCard key={item.construct} item={item} />
            ))}
          </div>

          <div className="insightGrid">
            <StrengthsList strengths={result.strengths} />
            <DevelopmentList areas={result.areas_for_improvement} />
          </div>

          <AiRecommendationPanel
            recommendation={result.ai_recommendation}
            source={result.recommendation_source}
            phase={phase}
          />

          <div className="researchNote">
            <strong>Research interpretation</strong>
            <p>
              The employability value is a continuous machine-learning prediction. Strength and
              development labels are used only to organize personalized guidance and are not
              separate ML classifications.
            </p>
          </div>

          <button className="secondaryButton" onClick={resetAssessment} type="button">
            Start New Assessment
          </button>
        </section>
      )}
    </div>
  );
}

export default function EmployabilityView({ onBackToDashboard }) {
  const [activePhaseId, setActivePhaseId] = useState(null);
  const [statuses, setStatuses] = useState({});

  useEffect(() => {
    let cancelled = false;
    Promise.all(
      EMPLOYABILITY_PHASES.map(async (phase) => {
        try {
          await checkEmployabilityHealth(phase.id);
          return [phase.id, true];
        } catch {
          return [phase.id, false];
        }
      })
    ).then((entries) => {
      if (!cancelled) setStatuses(Object.fromEntries(entries));
    });
    return () => {
      cancelled = true;
    };
  }, []);

  const activePhase = activePhaseId ? getEmployabilityPhaseById(activePhaseId) : null;

  return (
    <div className="module-view-wrapper employability-view">
      <div className="view-subbar">
        <button
          className="back-dashboard-btn"
          onClick={activePhase ? () => setActivePhaseId(null) : onBackToDashboard}
        >
          <ArrowLeft size={16} /> {activePhase ? "Back to phase selection" : "Back to Home"}
        </button>
        <span className="view-tag">
          <Sparkles size={14} /> Employability Simulator (Behaviour-Aware Career Simulation)
        </span>
      </div>

      <div className="app">
        <main>
          {activePhase ? (
            <PhaseAssessmentPanel phase={activePhase} />
          ) : (
            <PhaseSelectorPanel statuses={statuses} onSelect={setActivePhaseId} />
          )}
        </main>
      </div>
    </div>
  );
}
